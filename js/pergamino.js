export const FIRMA = "Lía, la de la primera piedra";

const ROMANOS = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII"];

// Todo el pergamino con el nombre puesto. Devuelve
// { titulo, subtitulo, prologo, capitulos: [{ numero, titulo, parrafos }], ensenanzas, dedicatoria, firma, minutos }
export function pergaminoPara(nombre) {
    const poner = (texto) => texto.replaceAll("{n}", nombre);
    const capitulos = CAPITULOS.map((c, i) => ({ numero: ROMANOS[i], titulo: c.titulo, parrafos: c.parrafos.map(poner) }));
    const dedicatoria = DEDICATORIA.map(poner);
    return {
        titulo: TITULO,
        subtitulo: SUBTITULO,
        prologo: PROLOGO,
        capitulos,
        ensenanzas: ENSENANZAS,
        dedicatoria,
        firma: FIRMA,
        minutos: minutosDeLectura(),
    };
}

// Cuántas palabras tiene (para decir cuánto se tarda en leerlo).
export function palabras() {
    const todo = [...PROLOGO, ...CAPITULOS.flatMap((c) => [c.titulo, ...c.parrafos]), ...ENSENANZAS, ...DEDICATORIA].join(" ");
    return todo.split(/\s+/).filter(Boolean).length;
}

// Unas 200 palabras por minuto, leyendo con calma.
export function minutosDeLectura() {
    return Math.max(1, Math.round(palabras() / 200));
}
